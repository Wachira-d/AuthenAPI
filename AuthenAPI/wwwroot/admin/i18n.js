const LANG_KEY = 'authenapi.admin.lang';
let lang = 'th';
try {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === 'en' || saved === 'th') lang = saved;
} catch { /* storage disabled */ }

export function getLang() { return lang; }

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'th';
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
}

/** BCP-47 locale for Intl. Thai uses the Gregorian calendar so years match log files. */
export function locale() { return lang === 'th' ? 'th-TH-u-ca-gregory' : 'en-GB'; }

export function has(key) { return key in STRINGS[lang] || key in STRINGS.en; }

export function t(key, vars) {
  let s = STRINGS[lang][key];
  if (s === undefined) s = STRINGS.en[key];
  if (s === undefined) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

document.documentElement.lang = lang;
